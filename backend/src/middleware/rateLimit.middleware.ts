import rateLimit from 'express-rate-limit';

export const publicInquiryLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 20,
  standardHeaders: true,
  legacyHeaders: false,
  skip: () => process.env.NODE_ENV === 'test',
  message: {
    success: false,
    message: 'Too many inquiries submitted from this IP address. Please try again in 15 minutes.',
  },
});

